# Perform addition, subtraction, multiplication, and division on two numbers provided by the user.

# Example code to calculate the area of a rectangle
length = float(input("Enter the length of the rectangle: "))
width = float(input("Enter the width of the rectangle: "))
area = length * width
addition = length + width
subtraction = length - width
multiplication = length * width
division = length / width
# Print the results
print(f"The length is: {length}")
print(f"The width is: {width}")
print(f"The addition of length and width is: {addition}")
print(f"The subtraction of length and width is: {subtraction}")
print(f"The multiplication of length and width is: {multiplication}")
print(f"The division of length by width is: {division}")
# The area of the rectangle is calculated by multiplying the length and width.
# Print the area of the rectangle
print(f"The area of the rectangle is: {area}")